/** 研报体裁词（中文） */
const REPORT_GENRE =
  /(研报|研究报告|深度报告|策略报告|周报|月报|季报|年报|半年报|专题报告|行业报告|点评|简评|跟踪报告|投资策略|投资价值|行业比较|前瞻|展望|追踪|跟踪|白皮书|路演|调研纪要|行业前景|业绩前瞻|业绩复盘|估值锚|超额收益)/;

/**
 * 英文研报标题的特征词。
 *
 * ⚠️ 这个正则**必须保持窄**。第一版把 `AI|Model|Global|China` 之类的宽词也放进去，
 * 结果标题里带「AI」的中文课程分享（`3.5上午 - Ai应用论坛`）和
 * 带 `The Model Race` 的英文报告一起被判成研报，把「课程资源」全吞了。
 *
 * 教训：**英文词只用真正表征「研究报告」的词**，
 * 通用大词（AI、Model、Global、China）在中文语境下区分度几乎为零。
 */
const REPORT_GENRE_EN =
  /\b(Outlook|Review|Preview|Strategy|Fundamentals?|Valuation|Semi(?:conductor)?|Machine|Race|Pricing|Adoption|Forecast|Quarterly|Annual|Monthly|Weekly|Report|Research|Equity Research)\b/i;

/**
 * 会议纪要/电话会议类 —— **归「数据」而不是「研报」**。
 *
 * 理由：纪要是**原始信息记录**（谁说了什么），不是机构的分析结论。
 * 把它当研报会让「研报」这个类目混入非分析性材料。
 */
const MINUTES_GENRE = /(电话会议|会议全文|纪要|实录|速记|对话全文|Q\&A|纪要全文)/;

/**
 * 书籍/教材体裁词 */
const BOOK_GENRE =
  /(教材|讲义|读本|书籍|专著|手册|指南|入门|概论|原理|教程|共读|第\s*\d+\s*版|译|经典|全集|文集)/;

/**
 * 「书名号 + 作者署名」的电子书命名法 —— 归「电子书籍」。
 *
 * 素材库里流传的电子书典型长相是：
 * `《涛动周期论：经济周期决定人生财富命运》周金涛(1).pdf`
 * —— 书名号闭合后紧跟作者署名，再跟一个卷/册序号。
 *
 * ⚠️ 不能简化成「带书名号就是书」：`《中国供电发展报告（2026）》` 同样用书名号，
 * 但它是行业报告，必须留在「研报」。判据要落在**书名号之后还有没有署名**：
 * 报告的年份「（2026）」写在书名号**内部**，闭合后即结束；电子书后面还挂着作者名与序号。
 * 所以这里要求署名出现在标题**末尾**，且允许可选的一位数~两位数卷册号。
 *
 * 字符集里必须带上间隔号 `·`/`・`：外国作者署名常写成「查理·芒格」，
 * 只放行 `\u4e00-\u9fa5` 会让这一类书整个漏掉。
 */
const BOOKSIGN_BYLINE =
  /(》|」|”)\s*[\u4e00-\u9fa5·・]{2,8}\s*(?:[(（]\s*\d{1,2}\s*[)）])?\s*$/;

/**
 * 教材/工具书的**标题补充特征** —— 归「电子书籍」。
 *
 * 为什么需要单独一条：`BOOK_GENRE` 覆盖的是「教材」「第 2 版」这类**体裁判定词**，
 * 而 `手把手教你读财报-1/-2.pdf` 这类**工具书命名法**里一个都没有，
 * 于是被判成无体裁词 → 落到兜底的「研报」，读者在「电子书籍」里永远找不到它。
 *
 * ⚠️ 这条必须叠加「未命中课程体裁词」的条件（见 classifyItem 第 9 步），
 * 否则 `手把手教你做量化策略分享` 这类**课程**会被误升成书籍。
 */
const BOOK_TITLE_EXTRA = /(手把手|教你|读财报|一本书|图解|从零开始|入门到精通|实战手册)/;

/**
 * 尽调资料包 —— 归「社团成员产出」。
 *
 * 判定词很窄：只有 `DataRoom` / `尽调` / `尽职调查` 这几种写法。
 * 刻意**不**把「资料包」「调研」纳入：那是资料分发的通用词，
 * `培训资料包.zip` 显然是课程资源，不该被这条规则捞走。
 */
const DUE_DILIGENCE_GENRE = /(dataroom|data\s?room|尽调|尽职调查)/i;

/**
 * 「每日新闻」整理稿 —— 归「社团成员产出」。
 *
 * 这是**协会自己每日整理**的成果，而非外部研报；它与晨报类研报的差别在于
 * 前者是自产的汇编，后者是机构的分析结论。规则保持窄，只认最常见的两种叫法。
 */
const DAILY_NEWS_GENRE = /(每日新闻|每日资讯)/;

/**
 * 课程/分享体裁词。
 *
 * 除了「分享|培训|讲座」这类显式词，还要覆盖**培训部实际用的口语化命名**：
 * - `我们应该如何去看待当下的金融市场` —— 疑问句式的分享标题，无任何体裁词；
 * - `投行四百问` —— 「X百问 / X问」是培训答疑材料的口语惯用名；
 * - `26金投介绍` —— 「介绍 / 简介 / 概览」是宣讲材料。
 * 这些名字里都不含「分享/培训」，但显然不是券商研报，靠关键词补上。
 *
 * ⚠️ 疑问句要容错中间的虚词：`如何**去**看待` 里夹了个「去」，
 * 写死 `如何看` 会漏。故用 `如何.{0,2}看` 这类允许 0–2 个字的写法。
 */
const COURSE_GENRE =
  /(分享|培训|课程|讲座|课堂|公开课|研讨|沙龙|workshop|训练营|集训|系列课|讲解|教学|分享会|内部培训|论坛|介绍|简介|概览|年会|峰会|如何.{0,2}看|如何.{0,2}理解|怎么.{0,2}看|怎么.{0,2}理解|百问|问答|答疑|入门课|漫谈|闲谈|杂谈|随谈)/;

/** 数据类文件体裁词 */
const DATA_GENRE = /(数据|统计|指标|因子|跟踪|Excel|表格|数据库|dataset|样本|新闻)/;

/**
 * 校内行政/制度类文件 —— 归「课程资源」。
 *
 * 这类文件既不是研报也不是数据，但确实是协会资料的一部分，
 * 归到「课程资源」比丢进「研报」更不误导。
 */
const CAMPUS_DOC = /(西财大办|西南财经大学|管理[办法规定条例]|实施细则|章程|通知|公示|名单)/;

/**
 * 「日期 + 公司名」的券商公司报告命名法。
 *
 * 如 `2026-08-21 汇川技术(A)`、`2026-08-28 中国中车(A)`：
 * 没有机构名也没有体裁词，但这是**券商个股报告最常见的命名格式**。
 * 形如 `YYYY-MM-DD 或 YYYY.M.D` 开头、且标题里不含课程词，判为研报。
 */
const DATED_TITLE = /^\s*20\d{2}[-.\/年]\s?\d{1,2}[-.\/月]?\s?\d{0,2}/;

/** 压缩包扩展名——资料分发通常打包，按「课程资源」归档 */
const ARCHIVE_EXTS = new Set(['zip', 'rar', '7z', 'tar', 'gz']);

/** 表格类扩展名 → 数据 */
const DATA_EXTS = new Set(['xlsx', 'xls', 'csv', 'tsv']);

/** 电子书扩展名 → 电子书籍 */
const BOOK_EXTS = new Set(['epub', 'mobi', 'azw3', 'djvu']);

/**
 * 把一个文件归入展示类目。
 *
 * 判定按**从具体到宽泛**的顺序进行，第一个命中即返回。
 * 顺序本身是有意义的，几条关键取舍：
 *
 * - **扩展名优先于标题**：epub 就是电子书、xlsx 就是数据，
 *   比任何关键词都可靠，先判掉可以避免被标题里的「研报」等词带偏。
 * - **会议纪要先于研报**：纪要是原始记录而非分析结论，归「数据」。
 * - **校内行政文件先于研报**：否则兜底规则会把它们吞进「研报」。
 *
 * @param {{ name: string, ext: string, categoryDir: string }} file
 * @returns {string} 四类之一
 */
export function classifyItem({ name, ext, categoryDir }) {
  const title = String(name ?? '');
  const e = String(ext ?? '').toLowerCase();

  // 1) 扩展名给出最硬的信号
  if (BOOK_EXTS.has(e)) return '电子书籍';
  if (DATA_EXTS.has(e)) return '数据';

  // 1.5) 自产作品：尽调资料包 / 每日新闻整理稿 →「社团成员产出」
  //
  // **必须排在压缩包规则之前**：尽调资料包的实际分发形态就是 .rar / .zip，
  // 若先判扩展名，它们会被「压缩包一律按课件处理」吞进「课程资源」，
  // 于是「作者信息、作品简介」这类属于作品的属性全部无处安放。
  if (DUE_DILIGENCE_GENRE.test(title) || DAILY_NEWS_GENRE.test(title)) {
    return PRODUCTION_CATEGORY;
  }

  // 2) 压缩包：资料分发形态，归「课程资源」
  if (ARCHIVE_EXTS.has(e)) return '课程资源';

  // 2.5) 电子书命名法（`《书名》作者(卷号)`）→「电子书籍」。
  //
  // **必须排在研报规则之前**：书名里常带「投资策略」「周期」这类词，
  // 一旦先跑 REPORT_GENRE，书就会被当成研报捞走，读者在「电子书籍」里永远找不到。
  // 放在压缩包规则之后，是为了不打破「压缩包一律按分发形态归档」这条既有直觉。
  if (BOOKSIGN_BYLINE.test(title)) return '电子书籍';

  // 3) 会议纪要 / 电话会议实录 → 原始信息，归「数据」
  if (MINUTES_GENRE.test(title)) return '数据';

  // 4) 校内行政文件
  if (CAMPUS_DOC.test(title)) return '课程资源';

  // 5) 研报：权威机构、中文研报体裁，或英文研报特征词
  if (
    RESEARCH_HOUSE.test(title) ||
    REPORT_GENRE.test(title) ||
    REPORT_GENRE_EN.test(title)
  ) {
    return '研报';
  }

  // 6) 「日期 + 标题」命名法：券商公司报告的常见格式，如
  //    `2026-08-21 汇川技术(A)`。放在课程词之前判，否则会被
  //    兜底的课程规则吞掉 —— 这类名字里没有任何课程词，但它就是研报。
  if (DATED_TITLE.test(title)) return '研报';

  // 7) 书籍体裁词
  if (BOOK_GENRE.test(title)) return '电子书籍';

  // 7.5) 工具书命名法（如「手把手教你读财报-2」）。
  //      叠加「未命中课程体裁词」的条件，避免把课程分享误升成书籍。
  if (BOOK_TITLE_EXTRA.test(title) && !COURSE_GENRE.test(title)) return '电子书籍';

  // 8) 培训/课程类 —— **只看标题，不看目录名**。
  //
  // 这里曾经写成 `COURSE_GENRE.test(title) || COURSE_GENRE.test(categoryDir)`，
  // 因为「培训部分享资料」这个目录名本身就命中「培训|分享」，
  // 于是该目录下**每一个**未命中的文件都落进「课程资源」，
  // 连 `425453630132f68bb43d9fb53c9db706.pdf` 这种哈希名的研报也不例外。
  // 目录只是归档位置，不能当作体裁证据 —— 否则兜底规则形同虚设。
  if (COURSE_GENRE.test(title)) return '课程资源';

  // 9) 名字里带「数据/统计」等词但扩展名是 pdf 的
  if (DATA_GENRE.test(title)) return '数据';

  // 10) 兜底：素材库主体是研报，兜底进「研报」比丢进「其他」更接近实际。
  return '研报';
}

