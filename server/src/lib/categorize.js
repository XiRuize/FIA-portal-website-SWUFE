/**
 * 资料展示类目归类。
 *
 * ## 背景
 *
 * 素材目录 `资料分享模块素材/` 是按**存放位置**组织的（培训部分享资料 / 研发部内部资料 / logo），
 * 这是给整理者看的；而读者关心的是**内容形态**。两者不是一回事：
 * 「研发部内部资料」里同时装着研报 PDF、Excel 数据、电子书 EPUB 和 rar 压缩包。
 *
 * 因此这里引入「展示类目」这一层，与磁盘目录解耦：
 *
 * | 展示类目 | 判定依据 |
 * | --- | --- |
 * | 研报 | 券商/投行研报：来源机构名、周报/月报/策略/点评等词 |
 * | 数据 | xlsx/xls/csv，以及名字里带数据/统计/因子/跟踪的 |
 * | 电子书籍 | epub 扩展名；教材/讲义/第 N 版等体裁词；`《书名》作者(卷号)` 命名法 |
 * | 课程资源 | 培训分享、课程、讲座、教程、入门手册、压缩包资料 |
 *
 * ## 两条硬约束
 *
 * 1. **logo 不进「资料与数据」**。企业 logo 是首页「会友去向」的素材，
 *    不是给会员下载的资料。`isLibraryItem()` 会把它们排除在清单之外，
 *    但它们**仍留在数据库里**（首页要用），只是不参与资料列表与类目统计。
 * 2. **「全部」= 四个实类目之和**，不含「其他」。这样「全部」的数字与
 *    四个分类数字相加自洽，读者不会看到「全部 68、分项加起来只有 60」这种困惑。
 */

/** 四个实类目（「全部」是它们的并集，不是独立类目）—— 服务于「资料与数据」页面 */
export const LIBRARY_CATEGORIES = ['电子书籍', '数据', '研报', '课程资源'];

/**
 * 「社团成员产出」类目。
 *
 * 它**不属于**「资料与数据」的四个类目，而是另一条独立的产品线：
 * 「资料与数据」承载的是**外部资料**（券商研报、教材、数据表、课程讲义），
 * 「社团成员产出」承载的是**协会自己人做出来的作品**（尽调资料包、每日新闻整理、
 * 研究报告、估值模型等）。
 *
 * 为什么必须分开而不是并列成第 5 个标签：
 * 1. 两者的**读者心智不同** —— 前者是「找资料参考」，后者是「看同学做了什么」；
 * 2. 前者有「全部 = 四类之和」的口径约束，掺进来源不同的作品会让合计失去意义；
 * 3. 后者要按「作品」渲染（作者、截图、分享），交互形态与文件列表完全不同。
 *
 * 因此这里用「模块（module）」切分，而不是继续往 LIBRARY_CATEGORIES 里加项。
 */
export const PRODUCTION_CATEGORY = '社团成员产出';

/** 「社团成员产出」模块下的实体类目（目前一个，保留为数组便于将来细分） */
export const PRODUCTION_CATEGORIES = [PRODUCTION_CATEGORY];

/**
 * 「社团成员产出」页面的**部门导航**。
 *
 * ⚠️ 这里的每一项都**不是**一个新的展示类目 —— 展示类目始终只有
 * `PRODUCTION_CATEGORY` 一个（上面那个数组刻意保持单元素）。
 * 部门是叠在「社团成员产出」模块**内部**的一层**纵向筛选**，
 * 与「资料与数据」页的「电子书籍 / 数据 / 研报 / 课程资源」横向类目是两回事：
 *
 * - **横向（display_category）决定一条记录属于哪个模块**，
 *   是 `moduleScope()` 的数据隔离依据，写错会让两个页面互相串台；
 * - **纵向（department）只在已确定属于产出模块的记录里再切一刀**，
 *   切错最坏的结果只是某个部门的标签少一条作品，不会越界。
 *
 * 因此部门**必须允许为空**：一条产出可能还没标部门（或作者是跨部门小组），
 * 这类记录归入「全部」但不出现在任何具体部门下。若把它当成必填的展示类目，
 * 就会出现「没写部门的作品从产出页彻底消失」这种数据静默丢失。
 *
 * 顺序即前端标签顺序，`全部` 由前端补在最前，故不写在这里。
 */
export const PRODUCTION_DEPARTMENTS = ['研发部', '培训部', '宣传中心'];

/** 全部展示类目（两个模块的并集），仅用于「取值必须在白名单内」这类校验 */
export const ALL_DISPLAY_CATEGORIES = [...LIBRARY_CATEGORIES, ...PRODUCTION_CATEGORIES];

/**
 * 展示模块定义。前端标签栏、后端列表过滤都以这里为准，避免两端各写一份。
 */
export const MODULES = {
  library: {
    id: 'library',
    label: '资料与数据',
    categories: LIBRARY_CATEGORIES,
    /** 该模块下「全部」的含义：四类之和 */
    countAllAsSum: true,
  },
  productions: {
    id: 'productions',
    label: '社团成员产出',
    categories: PRODUCTION_CATEGORIES,
    countAllAsSum: true,
  },
};

/** 某个展示类目归属哪个模块 */
export function moduleOfCategory(name) {
  return PRODUCTION_CATEGORIES.includes(String(name)) ? 'productions' : 'library';
}

/** 「全部」标签的展示名 */
export const ALL_CATEGORY = '全部';

/**
 * 不属于资料库的分类目录。
 * logo 是首页视觉素材，不该混进「资料与数据」的下载列表。
 */
export const NON_LIBRARY_DIRS = new Set(['logo']);

/** 是否是资料库条目（决定它出不出现在「资料与数据」页） */
